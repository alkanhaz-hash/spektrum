export function normalizeLocale(value?: string | null): Locale | null {
  if (!value) return null;
  const normalized = value.toLowerCase();
  if (normalized === "tr" || normalized.startsWith("tr-")) return "tr";
  if (normalized === "en" || normalized.startsWith("en-")) return "en";
  return null;
}

export function detectLocale(value?: string | null): Locale {
  return normalizeLocale(value) ?? "tr";
}

const allEnglish: Record<string, string> = Object.assign(Object.create(null), englishInfo, englishErrors, englishUi, englishAudio, english);
const normalizedEnglish = new Map(Object.entries(allEnglish).map(([key, value]) => [key.replace(/\s+/g, " ").trim(), value]));

export function translate(locale: Locale, source: string): string {
  if (locale !== "en") return source;
  const exact = allEnglish[source];
  if (exact !== undefined) return exact;
  const trimmed = source.trim();
  const match = normalizedEnglish.get(trimmed.replace(/\s+/g, " "));
  if (match !== undefined) return source.slice(0, source.indexOf(trimmed)) + match + source.slice(source.indexOf(trimmed) + trimmed.length);
  // Numeric UI helper output; these patterns are anchored, and are never
  // applied to story bodies, private messages, or other user-authored fields.
  const timeUnits: Record<string, string> = {
    "dakika önce": "minutes ago", "saat önce": "hours ago", "gün önce": "days ago", "hafta önce": "weeks ago",
    "dk önce": "minutes ago", "sa önce": "hours ago", "g önce": "days ago",
    dk: "min", sa: "h", sn: "s", g: "d", gün: "days", hafta: "weeks",
  };
  if (/^\d+\s*(?:dk|sa|sn|g|gün|hafta|dakika önce|saat önce|gün önce|hafta önce|dk önce|sa önce|g önce)(?:\s+\d+\s*(?:dk|sa|sn))*$/.test(trimmed)) {
    return trimmed.replace(/(\d+)\s*(dakika önce|saat önce|gün önce|hafta önce|dk önce|sa önce|g önce|hafta|gün|dk|sa|sn|g)/g, (_, count: string, unit: string) => `${count} ${timeUnits[unit]}`);
  }
  return translateUiTemplate(source) ?? source;
}

/** Notification grammar is localized independently of names and story titles. */
export function notificationSummary(locale: Locale, type: string, senderName: string): string {
  const messages: Record<string, [string, string]> = {
    follow: [`${senderName} seni takip etmeye başladı.`, `${senderName} started following you.`],
    like: [`${senderName} hikayeni beğendi.`, `${senderName} liked your story.`],
    comment: [`${senderName} hikayene yorum yaptı.`, `${senderName} commented on your story.`],
    qa_answer: [`${senderName} anonim sorunuzu yanıtladı.`, `${senderName} answered your anonymous question.`],
    chapter_approved: ["Bölümün onaylandı ve yayınlandı.", "Your chapter was approved and published."],
    chapter_rejected: ["Bölümün reddedildi.", "Your chapter was rejected."],
    moderator_directive: ["Moderatörden direktif:", "Instruction from a moderator:"],
  };
  return messages[type]?.[locale === "en" ? 1 : 0] ?? (locale === "en" ? "New notification." : "Yeni bildirim.");
}

